-- 042. Тонкая настройка того, когда наряд положен.
--
-- Расписание было только у многосуточной смены: пары «день заступления — день
-- сдачи». Ежедневный наряд считался положенным КАЖДЫЕ сутки, и наряд,
-- который несут по субботам, воскресеньям и понедельникам, задать было
-- нечем.
--
-- Теперь дни недели задаются и ежедневному наряду: пустой перечень означает
-- прежнее «каждые сутки», непустой — только перечисленные дни. Для смены
-- смысл прежний: день заступления и день сдачи.
--
-- Отдельно задается отношение к нерабочим дням — праздникам и выходным из
-- справочника (раздел 8.9.3). Дни недели этого не выражают: праздник среди
-- недели и рабочая суббота объявляются постановлением, а не календарем.

BEGIN;

ALTER TABLE duty.duty_types
    ADD COLUMN holiday_rule text NOT NULL DEFAULT 'any';

ALTER TABLE duty.duty_types
    ADD CONSTRAINT duty_types_holiday_rule_known
    CHECK (holiday_rule IN ('any', 'only', 'never'));

COMMENT ON COLUMN duty.duty_types.holiday_rule IS
    'Нерабочие дни: any — как обычно, only — наряд только в них, never — в них наряд не положен';

-- День сдачи нужен только смене. У ежедневного наряда строка расписания
-- означает «в этот день недели наряд положен», и второй день в ней тот же.
COMMENT ON TABLE duty.duty_type_schedules IS
    'Когда наряд положен: для смены — день заступления и день сдачи, для ежедневного — дни недели';

COMMIT;
