-- 033. Уточнение коэффициентов очереди.
--
-- При множителе нагрузки 1.0 подбор закрывал месяц наполовину. Причина в
-- равновесии: если человек ходит в наряд раз в семь суток, его готовность в
-- момент выбора равна семи, а накопленная за тридцать суток нагрузка — около
-- шести. Разность получается меньше порога, и рота целиком оказывается «ниже
-- порога» — при том, что люди свободны и допущены.
--
-- Нагрузка должна быть ПОПРАВКОЙ к готовности, а не равным ей слагаемым: она
-- разводит тех, кто одинаково давно не заступал, но ходит с разной частотой.
-- При множителе 0.3 человек возвращается в списки на третьи сутки после
-- наряда — отсыпной, день отдыха и снова в очередь.
UPDATE core.settings SET value = 0.3, updated_at = now()
 WHERE key = 'queue.workload_factor';
