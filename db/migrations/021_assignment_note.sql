-- 021. Примечание к назначению.
--
-- При утверждении приказа начальник службы заменяет отдельного человека и
-- поясняет замену: «заболел», «убыл в командировку», «привлечен приказом
-- № 118». Пояснение относится к КОНКРЕТНОМУ назначению, а не к наряду
-- целиком: в наряде двенадцать постов, и примечание к наряду не сказало бы,
-- кого из двенадцати оно касается.
--
-- Поля is_override/override_reason для этого не подходят: они означают
-- назначение ВОПРЕКИ правилам отбора (раздел 8.5), и ограничение
-- assignments_override_has_reason связывает их между собой. Обычная замена
-- нарушением не является.

ALTER TABLE duty.duty_assignments
    ADD COLUMN note     text,
    ADD COLUMN noted_by int REFERENCES core.users(id) ON DELETE SET NULL,
    ADD COLUMN noted_at timestamptz;

COMMENT ON COLUMN duty.duty_assignments.note IS
    'Примечание к назначению: причина замены, внесенная при утверждении приказа';
