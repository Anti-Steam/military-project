-- 038. Виды нарядов заводятся и настраиваются из интерфейса.
--
-- Три вида (ОО, СН, ОД) были заведены начальным наполнением, а их настройки
-- правились миграциями. Логика к кодам видов нигде не привязана — она
-- работает через признак kind, расписание и нормы отдыха, — поэтому вид
-- наряда можно открыть на правку целиком, не трогая код.
--
-- Настройки вида, которые уже есть и теперь правятся из интерфейса:
--   code, name                — обозначение и наименование
--   kind                      — ежедневный или многосуточная смена
--   start_time, duration_hours— час заступления и длительность
--   recovery_sleep_days       — отсыпной: привлечение ЗАПРЕЩЕНО
--   recovery_off_days         — выходной: привлечение ДОПУСКАЕТСЯ
--   rest_excludes_weekends    — отдых тянется до следующего рабочего дня
--   base_weight               — вес наряда для балансировки нагрузки
--   is_active                 — применяется ли
--   duty_type_schedules       — дни недели заступления и сдачи (для смены)
--   duty_type_permits         — общие допуски, обязательные для заступления
--
-- Новое здесь — ЗАСТУПЛЕНИЕ ПОДРЯД.

BEGIN;

-- Разрешение заступать снова, не выждав отдыха от предыдущего заступления.
-- Нужно двум случаям: наряд, который по своей природе несут ежедневно, и
-- крайний случай, когда людей не хватает и начальник осознанно ставит того же
-- человека снова.
--
-- Разрешение снимает РОВНО ДВА ограничения и только для отдыха, порожденного
-- ЭТИМ ЖЕ нарядом: запрет по отсыпному и порог очереди, который прячет
-- сменившегося из списков. Отдых от других нарядов, допуски, отсутствия,
-- занятость и оружие остаются в силе — они про другое.
ALTER TABLE duty.duty_types
    ADD COLUMN allow_consecutive boolean NOT NULL DEFAULT false;

COMMENT ON COLUMN duty.duty_types.allow_consecutive IS
    'Можно заступать в этот наряд подряд, не выждав отдыха от него же';

-- У поста — то же, но точечно, и с третьим состоянием: NULL означает «как у
-- вида наряда». Пост часто исключение из общего правила, и заводить ради
-- одного поста отдельный вид наряда было бы нелепо.
ALTER TABLE duty.duty_posts
    ADD COLUMN allow_consecutive boolean;

COMMENT ON COLUMN duty.duty_posts.allow_consecutive IS
    'Заступление подряд: true — можно, false — нельзя, NULL — как у вида наряда';

-- Право на справочник видов нарядов. Отдельно от постов: вид наряда задает
-- правила, по которым живет весь график, и менять их вправе не всякий, кому
-- поручено вести перечень постов.
INSERT INTO core.permissions (code, name, section, sort_order) VALUES
    ('dutytype.manage', 'Справочник видов нарядов', 'Справочники', 55);

INSERT INTO core.role_permissions (role_code, permission_code) VALUES
    ('admin', 'dutytype.manage'), ('deputy', 'dutytype.manage');

COMMIT;
