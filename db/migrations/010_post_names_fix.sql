-- ============================================================================
-- 010_post_names_fix.sql
-- Исправление наименований постов, относящихся к ротам.
--
-- В миграции 008 наименование склеивалось из краткого имени подразделения,
-- отчего получалось «Дежурный по 1 рота». Наименования постов попадают
-- в приказ, поэтому форма должна быть правильной.
-- ============================================================================

BEGIN;

UPDATE duty.duty_posts
   SET name = replace(name, 'по 1 рота', 'по 1-й роте')
 WHERE name LIKE '%по 1 рота%';

UPDATE duty.duty_posts
   SET name = replace(name, 'по 2 рота', 'по 2-й роте')
 WHERE name LIKE '%по 2 рота%';

COMMIT;
