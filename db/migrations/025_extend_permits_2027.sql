-- 025. Продление синтетических допусков на 2027 год.
--
-- Допуски стенда выдавались со сроками внутри 2026 года, и уже с марта 2027
-- кандидатов не оставалось: медицинский допуск УМО/ВВК истекал у всех до
-- одного. Показать работу системы на горизонте года было невозможно.
--
-- Продлеваются только ДЕЙСТВУЮЩИЕ и еще не истекшие допуски. Записи, которые
-- истекли или приостановлены, остаются как есть: на них держатся проверки
-- «нет действующего допуска» и «допуск проверяется на дату заступления»
-- (раздел 7.2). Стенд без отрицательных случаев проверять нечем.
--
-- Сроки разносятся по сотрудникам, а не ставятся одной датой: одинаковый
-- срок у всех означал бы, что назавтра после него не годен никто, — и
-- напоминания об истечении проверить было бы не на чем.

-- Основная часть: годны весь 2027 год, истекают в течение 2028.
UPDATE personnel.employee_permits ep
   SET expires_at = DATE '2028-01-15' + ((ep.employee_id * 37) % 365),
       updated_at = now()
 WHERE ep.status = 'active'
   AND ep.expires_at IS NOT NULL
   AND ep.expires_at >= CURRENT_DATE
   AND ep.expires_at < DATE '2028-01-01'
   AND ep.employee_id % 23 <> 0;

-- Небольшая часть истекает ВНУТРИ 2027 года: без них нечем было бы
-- проверить, что допуск сверяется с датой заступления, а не с сегодняшней.
UPDATE personnel.employee_permits ep
   SET expires_at = DATE '2027-04-15' + ((ep.employee_id * 11) % 60),
       updated_at = now()
 WHERE ep.status = 'active'
   AND ep.expires_at IS NOT NULL
   AND ep.expires_at >= CURRENT_DATE
   AND ep.expires_at < DATE '2028-01-01'
   AND ep.employee_id % 23 = 0;
