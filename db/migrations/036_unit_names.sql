-- 036. Наименования подразделений стенда.
--
-- В начальном наполнении (028) взводы и отделения назывались с полной
-- вложенностью: «1 взвод 1 рота», «1 отд. 1 взвод 1 рота». Пока подразделение
-- показывалось само по себе, это было незаметно; как только понадобился путь
-- («1 рота · 1 взвод 1 рота · 1 отд. 1 взвод 1 рота»), выяснилось, что рота
-- называется в нем трижды.
--
-- Вложенность задается СТРУКТУРОЙ, а не переписыванием ее в каждое имя: место
-- подразделения в дереве известно из parent_id, и повторять его в
-- наименовании значит хранить одно и то же дважды. Наименования приводятся к
-- собственным: «1 взвод», «1 отделение».
--
-- Там, где подразделения показываются плоским списком (выпадающие списки
-- перевода, закрепления, области видимости), путь подставляется запросом —
-- см. org/queries.listUnits.

BEGIN;

UPDATE core.units u
   SET short_name = substring(u.short_name from '^([0-9]+ взвод)'),
       name       = substring(u.short_name from '^([0-9]+ взвод)') || ' роты'
 WHERE u.short_name ~ '^[0-9]+ взвод [0-9]+ рота$';

UPDATE core.units u
   SET short_name = replace(substring(u.short_name from '^([0-9]+ отд\.)'), 'отд.', 'отделение'),
       name       = replace(substring(u.short_name from '^([0-9]+ отд\.)'), 'отд.', 'отделение')
 WHERE u.short_name ~ '^[0-9]+ отд\. ';

COMMIT;
