-- Заполнение справочников. Не содержит данных о людях.
--
-- Миграция идемпотентна: повторный запуск не создает дублей.
--
-- ВНИМАНИЕ. Значения, помеченные [УТОЧНИТЬ], приняты как предположение и
-- подлежат согласованию (раздел 13.2 ТЗ).
-- ============================================================================

BEGIN;

-- ----------------------------------------------------------------------------
-- Воинские звания. seniority задает старшинство для сортировки в приказах.
-- ----------------------------------------------------------------------------
INSERT INTO core.ranks (name, short_name, seniority) VALUES
    ('рядовой',             'р-й',    10),
    ('ефрейтор',            'ефр.',   20),
    ('младший сержант',     'мл. с-т', 30),
    ('сержант',             'с-т',    40),
    ('старший сержант',     'ст. с-т', 50),
    ('старшина',            'ст-на',  60),
    ('прапорщик',           'пр-к',   70),
    ('старший прапорщик',   'ст. пр-к', 80),
    ('младший лейтенант',   'мл. л-т', 90),
    ('лейтенант',           'л-т',    100),
    ('старший лейтенант',   'ст. л-т', 110),
    ('капитан',             'к-н',    120),
    ('майор',               'м-р',    130),
    ('подполковник',        'п/п-к',  140),
    ('полковник',           'п-к',    150)
ON CONFLICT (name) DO NOTHING;


-- ----------------------------------------------------------------------------
-- Виды допусков (раздел 7.1 ТЗ).
--
-- default_validity_months: 12 — год, 60 — пять лет, NULL — срок задается
-- индивидуально «от даты к дате».
-- [УТОЧНИТЬ] распределение сроков по видам допусков.
-- ----------------------------------------------------------------------------
INSERT INTO personnel.permit_types
    (code, name, default_validity_months, is_duty_specific, notify_days_before) VALUES
    -- Оформляется отдельно к каждому виду наряда, поэтому is_duty_specific = true.
    ('SN',        'Суточный наряд',                    12, true,  30),
    ('OO',        'Охрана и оборона',                  12, false, 30),
    ('WORK_CTRL', 'Контроль работ',                    12, false, 30),
    ('TECH',      'Работы с техникой',                 12, false, 30),
    ('UMO_VVK',   'УМО / ВВК (медицинский допуск)',    12, false, 30),
    ('MPFO',      'МПФО (допуск психолога)',           60, false, 60),
    -- Выдается непосредственно перед выполнением работ, срок «от даты к дате».
    ('DIRECT',    'Непосредственный допуск',         NULL, false, 7)
ON CONFLICT (code) DO NOTHING;


-- ----------------------------------------------------------------------------
-- Виды нарядов (раздел 8.1 ТЗ).
--
-- recovery_sleep_days — отсыпной, привлечение к другим нарядам ЗАПРЕЩЕНО.
-- recovery_off_days   — выходной, привлечение ДОПУСКАЕТСЯ.
-- ----------------------------------------------------------------------------
INSERT INTO duty.duty_types
    (code, name, kind, start_time, duration_hours,
     recovery_sleep_days, recovery_off_days, rest_excludes_weekends, base_weight) VALUES

    -- Многодневная смена: пятница→вторник либо вторник→пятница.
    -- 2 суток отдыха, не считая выходных.
    -- [УТОЧНИТЬ] время заступления; отнесение отдыха к отсыпному, а не к выходному.
    ('OO', 'Дежурная смена «Охрана и оборона»', 'multiday', '10:00', NULL,
     2, 0, true, 2.00),

    -- Суточный наряд: с 10:30 до 10:30 следующих суток.
    -- Отсыпной в день сдачи, выходной на следующий день.
    ('SN', 'Суточный наряд', 'daily', '10:30', 24,
     1, 1, false, 1.00),

    -- [УТОЧНИТЬ] расшифровка аббревиатуры «ОД».
    ('OD', 'ОД', 'daily', '10:00', 24,
     1, 1, false, 1.00)

ON CONFLICT (code) DO NOTHING;


-- ----------------------------------------------------------------------------
-- Варианты многодневных смен ОО.
-- Нумерация по ISO: 1 = понедельник … 5 = пятница … 7 = воскресенье.
-- В MVP не используется: наряд создается с явным указанием дат.
-- ----------------------------------------------------------------------------
INSERT INTO duty.duty_type_schedules (duty_type_id, start_weekday, end_weekday, start_time)
SELECT dt.id, v.start_wd, v.end_wd, dt.start_time
FROM duty.duty_types dt
CROSS JOIN (VALUES (5, 2), (2, 5)) AS v(start_wd, end_wd)
WHERE dt.code = 'OO'
  AND NOT EXISTS (
      SELECT 1 FROM duty.duty_type_schedules s
      WHERE s.duty_type_id = dt.id
        AND s.start_weekday = v.start_wd
        AND s.end_weekday = v.end_wd
  );


-- ----------------------------------------------------------------------------
-- Допуски, обязательные для заступления в наряд.
--
-- [УТОЧНИТЬ] состав требований по каждому виду наряда. Принято: медицинский
-- допуск и допуск психолога обязательны везде; профильный допуск — по виду.
-- ----------------------------------------------------------------------------
INSERT INTO duty.duty_type_permits (duty_type_id, permit_type_id)
SELECT dt.id, pt.id
FROM (VALUES
    ('OO', 'OO'), ('OO', 'UMO_VVK'), ('OO', 'MPFO'),
    ('SN', 'SN'), ('SN', 'UMO_VVK'), ('SN', 'MPFO'),
    ('OD', 'SN'), ('OD', 'UMO_VVK'), ('OD', 'MPFO')
) AS req(duty_code, permit_code)
JOIN duty.duty_types dt            ON dt.code = req.duty_code
JOIN personnel.permit_types pt     ON pt.code = req.permit_code
ON CONFLICT (duty_type_id, permit_type_id) DO NOTHING;


-- ----------------------------------------------------------------------------
-- Категории отсутствия (раздел 9.1 ТЗ). Перечень закрыт.
-- Командировка и учеба объединены в одну категорию.
-- Наряд в справочник не входит: он виден через duty.duty_assignments.
-- ----------------------------------------------------------------------------
INSERT INTO personnel.absence_types (code, name, blocks_duty, sort_order) VALUES
    ('VACATION', 'Отпуск',                true, 10),
    ('SICK',     'Больничный',            true, 20),
    ('TRIP',     'Командировка / учеба',  true, 30),
    ('DAY_OFF',  'Отгул',                 true, 40)
ON CONFLICT (code) DO NOTHING;

COMMIT;
