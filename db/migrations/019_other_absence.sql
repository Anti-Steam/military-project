-- ============================================================================
-- 019. Категория отсутствия «прочее» и авторство записей.
--
-- Начальник службы при утверждении наряда снимает человека, привлеченного к
-- работам, которых в системе нет (временный караул и подобное). Такой человек
-- считается ОТСУТСТВУЮЩИМ и выводится в строевой записке отдельной колонкой
-- «прочее», поэтому оформляется существующей сущностью отсутствия, а не новой:
-- фильтрация кандидатов по отсутствиям уже работает, и второй механизм
-- недоступности означал бы два места, где человека можно исключить.
--
-- Основание — приказ, отсутствующий в системе, поэтому его реквизиты
-- записываются в document_ref обязательно (проверяется на уровне приложения:
-- у остальных категорий основание может добавляться позже).
-- ============================================================================

INSERT INTO personnel.absence_types (code, name, blocks_duty, sort_order)
VALUES ('OTHER', 'Прочее (привлечение по отдельному приказу)', true, 50)
ON CONFLICT (code) DO NOTHING;


-- Автор записи об отсутствии. Нужен для разграничения прав: снятие человека
-- с наряда — действие начальника службы, и вышестоящим требуется видеть, кто
-- его выполнил. Поле заполняется уже сейчас, чтобы при появлении учетных
-- записей не пришлось восстанавливать авторство задним числом.
ALTER TABLE personnel.absences
    ADD COLUMN created_by int REFERENCES core.users(id) ON DELETE SET NULL;

COMMENT ON COLUMN personnel.absences.created_by IS
    'Кто внес запись. Заполняется при вводе через интерфейс; у данных, '
    'загруженных из приказов (МС-3), остается пустым.';


-- Кем снято назначение с поста. Само назначение удаляется, но факт снятия
-- относится к наряду, а не к человеку, поэтому фиксируется здесь.
ALTER TABLE duty.duties
    ADD COLUMN unapproved_by int REFERENCES core.users(id) ON DELETE SET NULL;

ALTER TABLE duty.duties
    ADD COLUMN unapproved_at timestamptz;

COMMENT ON COLUMN duty.duties.unapproved_by IS
    'Кто снял утверждение. Утверждение снимается при обнаружении ошибки в '
    'составе; сам факт должен оставаться видимым вышестоящим.';
