-- ============================================================================
-- 005_oo_start_time.sql
-- Время заступления дежурной смены «Охрана и оборона».
--
-- Согласовано: заступление в 17:30.
-- Смена многодневная: пятница 17:30 → вторник 17:30 либо
--                     вторник 17:30 → пятница 17:30.
--
-- Подтверждено также правило отдыха: 2 суток отдыха после смены отсчитываются
-- только по рабочим дням — суббота и воскресенье в эти двое суток не входят.
-- Соответствует rest_excludes_weekends = true, установленному в миграции 002.
-- ============================================================================

BEGIN;

UPDATE duty.duty_types
   SET start_time = '17:30'
 WHERE code = 'OO';

-- Варианты расписания многодневной смены хранят собственное время заступления.
UPDATE duty.duty_type_schedules s
   SET start_time = '17:30'
  FROM duty.duty_types dt
 WHERE s.duty_type_id = dt.id
   AND dt.code = 'OO';

COMMIT;
