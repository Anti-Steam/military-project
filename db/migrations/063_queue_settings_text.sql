-- Пояснения к настройкам подбора — по тому, как их считает код (решение 157).
-- Готовность теперь считается от суток СДАЧИ последнего наряда, а не от
-- заступления; надбавка — тем, кто не заступал НИ РАЗУ (а не «за период»).

UPDATE core.settings SET
  name = 'Наименьший простой после сдачи, суток',
  description = 'Сколько суток после сдачи последнего наряда должно пройти, чтобы человек снова предлагался. '
    || '1 — нельзя только в сутки сдачи, со следующих можно; 2 — еще сутки паузы. Это порог: не прошедший '
    || 'его в списке не показывается. Где разрешено заступление подряд, порог не действует.'
WHERE key = 'queue.min_days_off';

UPDATE core.settings SET
  name = 'Потолок готовности, суток',
  description = 'Каждые сутки простоя после сдачи прибавляют к очереди единицу, но не больше этого числа. '
    || 'Без потолка вернувшийся из отпуска месяцами вытеснял бы остальных. Ни разу не заступавший '
    || 'получает потолок сразу.'
WHERE key = 'queue.ready_max_days';

UPDATE core.settings SET
  name = 'Надбавка ни разу не заступавшим',
  description = 'Прибавляется к потолку готовности тому, у кого нет ни одного наряда за все время учета '
    || '(новичок, только что принятый). 0 — новичок наравне с давно не ходившим; больше 0 — идет первым.'
WHERE key = 'queue.unassigned_bonus';

UPDATE core.settings SET
  name = 'Вес накопленной нагрузки',
  description = 'Нагрузка — сумма весов нарядов за 30 суток до заступления: наряд в рабочий день — вес его '
    || 'вида, в выходной или праздник — ×1,5, плюс 0,5 за каждые сутки отсыпного. Очередь понижается на '
    || 'нагрузку × это число. 0 — частота не учитывается; 1 — нагрузка весит как готовность.'
WHERE key = 'queue.workload_factor';
