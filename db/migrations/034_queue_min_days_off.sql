-- 034. Порог предложения считается по ПРОСТОЮ, а не по итоговой очереди.
--
-- Порог по итоговой очереди возвращал человека в списки на третьи сутки:
-- накопленная нагрузка вычиталась из готовности, и первые двое суток очередь
-- не дотягивала до порога. Правило же простое — нельзя заступать только сразу
-- после смены, а на следующие сутки уже можно.
--
-- Поэтому порог задается в СУТКАХ ПРОСТОЯ и сравнивается с готовностью.
-- Нагрузка и соответствие посту продолжают влиять на ПОРЯДОК кандидатов, но
-- никого не отсекают: смешивать «кого предпочесть» с «кого нельзя» — значит
-- получать необъяснимые исчезновения людей из списка.
DELETE FROM core.settings WHERE key = 'queue.threshold';

INSERT INTO core.settings (key, value, name, description) VALUES
    ('queue.min_days_off', 1, 'Наименьший простой, суток',
     'Сколько суток должно пройти после заступления, чтобы человек снова предлагался. 1 — нельзя только в сутки сдачи, со следующих можно');
